# core/trait_sampler.py
"""
Latent-trait + response-style sampler for silicon sampling.

Target population (this study): **urban Iranian adults, 18-40 years old**,
answering a comprehensive **personality / mental-health inventory** that
screens for personality-disorder traits (avoidant, dependent, obsessive-
compulsive, paranoid, schizotypal, schizoid, histrionic, narcissistic,
borderline, antisocial) plus PID-5-style Likert facets, an attachment
module, and a psychotic-like-experiences frequency module.

Each synthetic respondent's standing on six relationship/personality latent
traits is drawn from a continuous multivariate-normal distribution with a
literature-plausible correlation structure, generated by a simple 3-factor
model:

    theta_dim = L[dim] . f  +  u_dim * e_dim ,     f ~ N(0, I_3), e ~ N(0, 1)

which yields standardized traits whose covariance is  Sigma = L L' + diag(u^2)
with unit variances — guaranteed positive-semidefinite by construction, no
numpy/Cholesky needed.

Common factors:
    f[0] = INT  : internalizing / distress proneness
                  (drives emotional instability, detachment/suspicion,
                   rigid perfectionism)
    f[1] = EXT  : externalizing / antagonism proneness
                  (drives impulsivity-antisociality, narcissism/attention)
    f[2] = PSY  : psychoticism / reality-distortion proneness
                  (drives unusual experiences, weakly emotional instability
                   and impulsivity)

The six latent traits (matching the persona-generation prompt and the
`details` prose schema):

    emotional_instability    — borderline traits: fear of abandonment,
                               dependency, mood swings, social anxiety,
                               feeling inadequate
    detachment_suspicion     — schizoid/paranoid: preferring to be alone,
                               holding grudges, distrusting others,
                               feeling watched/talked about, flat affect
    impulsivity_antisocial   — conduct/antisocial: childhood rule-breaking,
                               temper, recklessness, manipulation, low empathy
    narcissism_attention     — narcissistic/histrionic: superiority,
                               center of attention, entitlement,
                               exploitativeness, attention-seeking
    rigidity_perfectionism   — OCPD: details, order, hoarding, difficulty
                               delegating, rigid rules
    unusual_experiences      — schizotypal/psychotic-like: superstitions,
                               sixth sense, depersonalization, mild
                               hallucination-like experiences

Each respondent also gets response-STYLE parameters (acquiescence, extreme vs.
midpoint tendency, carelessness) so the eventual answers carry realistic METHOD
VARIANCE and measurement error rather than being a deterministic function of the
trait — the single biggest reason LLM survey data shows inflated Cronbach's
alpha and over-clean correlation matrices.

Pure standard library. Seedable for reproducibility.
"""

from __future__ import annotations

import math
import random
from typing import Dict, List


# ---------------------------------------------------------------------------
# Latent dimensions and their loadings on the three common factors.
# Order of factor loadings: (INT_internalizing, EXT_externalizing, PSY_psychoticism)
# Sign of a loading encodes direction. Sum of squared loadings must stay < 1 so
# uniqueness u > 0.
# ---------------------------------------------------------------------------

LOADINGS: Dict[str, tuple] = {
    "emotional_instability":    (0.70,  0.05, 0.20),  # distress + mild psychoticism
    "detachment_suspicion":     (0.55, -0.10, 0.10),  # internalizing; low antagonism
    "impulsivity_antisocial":   (0.05,  0.65, 0.15),  # externalizing + mild psychoticism
    "narcissism_attention":    (-0.10,  0.70, 0.05),  # antagonism; slight neg distress
    "rigidity_perfectionism":   (0.45, -0.20, 0.05),  # anxious-compulsive; controlled (neg EXT)
    "unusual_experiences":      (0.20,  0.05, 0.72),  # psychoticism + mild distress
}

# Human-readable Persian band labels for prose rendering.
BAND_LABELS = [
    "خیلی پایین", "پایین", "کمی پایین", "متوسط", "کمی بالا", "بالا", "خیلی بالا",
]
# z-score cut points between the 7 bands.
BAND_CUTS = [-1.5, -0.9, -0.35, 0.35, 0.9, 1.5]

# Persian labels for each latent dimension (rendered into the persona / answer prompts).
DIM_LABELS_FA: Dict[str, str] = {
    "emotional_instability":    "بی‌ثباتی هیجانی و اضطراب (ترس از طرد، وابستگی، نوسانات خلق، اضطراب اجتماعی، احساس ناکافی)",
    "detachment_suspicion":     "انزوا و بدبینی (ترجیح تنهایی، کینه، بی‌اعتمادی، احساس غیبت/بدگمانی، کم‌اظهار عاطفی)",
    "impulsivity_antisocial":   "تکانشگری و هنجارشکنی (سابقه قوانین‌شکنی، طغیان خشم، رفتار تکانشی، کم‌همدلی)",
    "narcissism_attention":     "خودشیفتگی و نیاز به توجه (احساس برتری، مرکز توجه، استحقاق، سوءاستفاده از دیگران)",
    "rigidity_perfectionism":   "کمال‌گرایی و وسواس (جزئیات، نظم، احتکار، دشواری در سپردن کار، قواعد سخت‌گیرانه)",
    "unusual_experiences":      "تجربیات غیرعادی (خرافات، حس ششم، تجرد از بدن، تجربیات شبه‌روانی)",
}


def format_profile_fa(profile: Dict, dims: List[str] | None = None) -> str:
    """Render a respondent's demographics + the requested latent-trait bands as a readable Persian block.

    Uses ``.get`` everywhere so a profile that is missing a field (e.g. an old
    persona produced by a different sampler) degrades gracefully instead of
    raising ``KeyError``.
    """
    dims = dims or list(LOADINGS.keys())
    d = profile.get("demographics", {}) or {}
    gender = d.get("gender", "—")
    age = d.get("age", "—")
    marital = d.get("marital_status", "—")
    education = d.get("education_level", "—")
    occupation = d.get("occupation", "—")
    region = d.get("region", "—")
    economic = d.get("economic_situation", "—")
    psych = d.get("psych_problem", "—")

    lines = [
        f"دموگرافیک: {gender}، {age} ساله، {marital}، {education}، شغل {occupation}",
        f"منطقه: {region} | وضعیت اقتصادی: {economic} | سابقه بیماری روان‌پزشکی: {psych}",
        "سطح صفات (روی طیف ۷‌بَندی از «خیلی پایین» تا «خیلی بالا»):",
    ]
    bands = profile.get("latent_traits_band", {}) or {}
    for dim in dims:
        lines.append(f"  - {DIM_LABELS_FA.get(dim, dim)}: {bands.get(dim, '—')}")
    return "\n".join(lines)


