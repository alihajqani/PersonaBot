# core/trait_sampler.py
"""
Latent-trait + response-style sampler for silicon sampling.

Target population (this study): **young-adult Iranian internet users (≈19–40,
university-educated: کارشناسی and above)** answering a four-scale
psychological battery:

    1. Internet Addiction Test            (msc_1_6_*)  -> internet_addiction
    2. Parental Bonding — Care subscale    (msc_1_7_*)  -> parental_care
    3. Dysfunctional Attitudes             (msc_1_8_*)  -> dysfunctional_attitudes
    4. Loneliness / low social support     (msc_1_9_*)  -> loneliness

Each synthetic respondent's standing on these four latent traits is drawn from
a continuous multivariate-normal distribution with a literature-plausible
correlation structure, generated by a 3-factor model:

    theta_dim = L[dim] . f  +  u_dim * e_dim ,   f ~ N(0, I_3), e ~ N(0, 1)

yielding standardized traits whose covariance is Sigma = L L' + diag(u^2) with
unit variances — guaranteed positive-semidefinite by construction.

Common factors:
    f[0] = N   : general negative affect / psychological vulnerability
                 (loads + on internet_addiction, dysfunctional_attitudes,
                  loneliness; − on parental_care)
    f[1] = S   : secure-base / social connectedness
                 (loads + on parental_care; − on loneliness; mildly − on the
                 two coping-avoidance traits)
    f[2] = B   : behavioural compulsivity / digital engagement
                 (loads + on internet_addiction and dysfunctional_attitudes;
                  mildly + on loneliness as an escape route)

Each respondent also gets response-STYLE parameters (acquiescence, extreme vs.
midpoint tendency, carelessness) so the eventual answers carry realistic METHOD
VARIANCE and measurement error rather than being a deterministic function of
the trait.

The demographics are sampled to match the five demographic RADIO questions in
the current schema (age band, gender, education, marital status, daily
social-media use). Social-media use is CONDITIONED on the internet_addiction
trait so a persona's stated digital habits are consistent with her answers to
the IAT.

Pure standard library. Seedable for reproducibility.
"""

from __future__ import annotations

import math
import random
from typing import Dict, List

# ---------------------------------------------------------------------------
# Latent dimensions and their loadings on the three common factors.
# Order of factor loadings: (N_negative_affect, S_secure_base, B_compulsivity)
# Sum of squared loadings stays < 1 so uniqueness u > 0.
# ---------------------------------------------------------------------------

LOADINGS: Dict[str, tuple] = {
    "internet_addiction":      ( 0.50, -0.15,  0.60),  # distress + compulsivity ↑
    "parental_care":          (-0.35,  0.65, -0.10),  # secure base ↑ ; distress ↓ recall
    "dysfunctional_attitudes":( 0.45, -0.10,  0.40),  # distress + perfectionism ↑
    "loneliness":             ( 0.55, -0.45,  0.20),  # distress ↑ ; connection ↓
}

# Human-readable Persian band labels for prose rendering.
BAND_LABELS = [
    "خیلی پایین", "پایین", "کمی پایین", "متوسط", "کمی بالا", "بالا", "خیلی بالا",
]
# z-score cut points between the 7 bands.
BAND_CUTS = [-1.5, -0.9, -0.35, 0.35, 0.9, 1.5]

# Persian labels for each latent dimension (rendered into persona / answer prompts).
DIM_LABELS_FA: Dict[str, str] = {
    "internet_addiction":      "اعتیاد به اینترنت (استفاده‌ی وسواسی، صرف‌نظر از کار/خواب برای اینترنت، پنهان‌کاری)",
    "parental_care":           "محبت و مراقبت ادراک‌شده‌ی والدین (گرما، نوازش، تأیید، گفتگوی آزاد، اعتماد، امنیت)",
    "dysfunctional_attitudes": "نگرش‌های اختلال‌ساز (کمال‌گرایی، نیاز به تأیید، ارزشِ خودِ وابسته به دیگران)",
    "loneliness":              "تنهایی و کمبود حمایت اجتماعی (نبود هم‌دل، بیگانه‌ی خانواده و دوستان)",
}


def format_profile_fa(profile: Dict, dims: List[str] | None = None) -> str:
    """Render a respondent's demographics + the requested latent-trait bands as a
    readable Persian block."""
    dims = dims or list(LOADINGS.keys())
    d = profile["demographics"]
    lines = [
        f"دموگرافیک: {d['gender']}، {d['age_band']}، {d['education']}، {d['marital_status']}، "
        f"استفاده‌ی روزانه از فضای مجازی: {d['social_media_use']}",
        "سطح صفات (روی طیف ۷‌بَندی از «خیلی پایین» تا «خیلی بالا»):",
    ]
    bands = profile["latent_traits_band"]
    for dim in dims:
        lines.append(f"  - {DIM_LABELS_FA.get(dim, dim)}: {bands[dim]}")
    return "\n".join(lines)


# ---------------------------------------------------------------------------
# Demographic sampling frame — young-adult Iranian internet users, matching
# the five demographic RADIO options in the schema exactly.
# EDIT these to match your real recruitment frame (national statistics, your
# sample, etc.). All option strings below must stay byte-identical to the
# schema options so static_answers() emits valid answers.
# ---------------------------------------------------------------------------

AGE_BANDS = ["22-19 سال", "26-23 سال", "30-27 سال", "34-31 سال", "35 سال به بالا"]
SOCIAL_MEDIA_BANDS = [
    "کمتر از ۱ ساعت", "۱ تا ۳ ساعت", "۳ تا ۵ ساعت", "۵ تا ۷ ساعت", "بیشتر از ۷ ساعت",
]

GENDER_FRAME = [
    ("زن", 0.50),
    ("مرد", 0.50),
]

# Education: the schema only offers کارشناسی and above (no diploma / associate).
EDUCATION_FRAME = [
    ("کارشناسی", 0.55),
    ("کارشناسی ارشد", 0.30),
    ("دکتری", 0.15),
]

# Marital status conditioned on age (younger → mostly single).
MARITAL_FRAME_YOUNG = [("مجرد", 0.85), ("متاهل", 0.13), ("مطلقه / جداشده", 0.02)]
MARITAL_FRAME_MID   = [("مجرد", 0.55), ("متاهل", 0.40), ("مطلقه / جداشده", 0.05)]
MARITAL_FRAME_OLD   = [("مجرد", 0.30), ("متاهل", 0.60), ("مطلقه / جداشده", 0.10)]


def _age_to_band(age: int) -> str:
    if age <= 22:
        return AGE_BANDS[0]
    if age <= 26:
        return AGE_BANDS[1]
    if age <= 30:
        return AGE_BANDS[2]
    if age <= 34:
        return AGE_BANDS[3]
    return AGE_BANDS[4]


def _band(z: float) -> str:
    idx = 0
    for cut in BAND_CUTS:
        if z >= cut:
            idx += 1
    return BAND_LABELS[idx]


def _weighted_choice(rng: random.Random, items: List[tuple]):
    r = rng.random()
    cum = 0.0
    for label, w in items:
        cum += w
        if r <= cum:
            return label
    return items[-1][0]


def _sigmoid(x: float) -> float:
    if x >= 0:
        z = math.exp(-x)
        return 1.0 / (1.0 + z)
    z = math.exp(x)
    return z / (1.0 + z)


def _social_media_use(rng: random.Random, z_ia: float) -> str:
    """Daily social-media use band, conditioned on the internet_addiction trait:
    higher proneness → higher usage band. Keeps a persona's stated habits
    consistent with her IAT answers."""
    n = len(SOCIAL_MEDIA_BANDS)
    center = int(round(_sigmoid(z_ia) * (n - 1)))  # 0 .. n-1
    weights = []
    for i in range(n):
        dist = abs(i - center)
        weights.append(max(0.05, 1.0 / (1.0 + dist * 1.5)))  # peak at center
    total = sum(weights)
    r = rng.random() * total
    cum = 0.0
    for i, w in enumerate(weights):
        cum += w
        if r <= cum:
            return SOCIAL_MEDIA_BANDS[i]
    return SOCIAL_MEDIA_BANDS[-1]


def sample_respondent(rng: random.Random, index: int) -> Dict:
    """Draw one synthetic respondent: latent traits + response style + demographics."""
    # --- common factors ---
    N = rng.gauss(0, 1)   # negative affect
    S = rng.gauss(0, 1)   # secure-base / social connectedness
    B = rng.gauss(0, 1)   # behavioural compulsivity
    f = (N, S, B)

    traits_z: Dict[str, float] = {}
    traits_band: Dict[str, str] = {}
    for dim, load in LOADINGS.items():
        ssq = sum(l * l for l in load)
        u = math.sqrt(max(1e-6, 1.0 - ssq))
        z = sum(l * fi for l, fi in zip(load, f)) + u * rng.gauss(0, 1)
        traits_z[dim] = round(z, 3)
        traits_band[dim] = _band(z)

    # --- response styles (method variance) ---
    response_style = {
        # >0 leans agree/high regardless of content; <0 leans disagree/low
        "acquiescence": round(rng.gauss(0, 0.40), 3),
        # >0 prefers extreme categories; <0 hugs the midpoint
        "extreme_response": round(rng.gauss(0, 0.40), 3),
        # rare inattentive responder (near-random / straightlining)
        "careless": rng.random() < 0.04,
    }

    # --- demographics: matched to the five schema demographic questions ---
    age = rng.randint(19, 40)
    age_band = _age_to_band(age)
    gender = _weighted_choice(rng, GENDER_FRAME)
    education = _weighted_choice(rng, EDUCATION_FRAME)
    if age <= 24:
        marital_status = _weighted_choice(rng, MARITAL_FRAME_YOUNG)
    elif age <= 30:
        marital_status = _weighted_choice(rng, MARITAL_FRAME_MID)
    else:
        marital_status = _weighted_choice(rng, MARITAL_FRAME_OLD)
    social_media_use = _social_media_use(rng, traits_z["internet_addiction"])

    return {
        "id": f"persona_{index}",
        "latent_traits_z": traits_z,
        "latent_traits_band": traits_band,
        "response_style": response_style,
        "demographics": {
            "age": age,
            "age_band": age_band,
            "gender": gender,
            "education": education,
            "marital_status": marital_status,
            "social_media_use": social_media_use,
        },
    }


def sample_population(n: int, seed: int | None = None) -> List[Dict]:
    """Draw n synthetic respondents."""
    rng = random.Random(seed)
    return [sample_respondent(rng, i + 1) for i in range(n)]


# ---------------------------------------------------------------------------
# Self-test / demo:  python -m core.trait_sampler 2000
# Prints empirical correlations to confirm the intended structure emerges.
# ---------------------------------------------------------------------------

def _corr(xs: List[float], ys: List[float]) -> float:
    n = len(xs)
    mx = sum(xs) / n
    my = sum(ys) / n
    sxy = sum((x - mx) * (y - my) for x, y in zip(xs, ys))
    sxx = sum((x - mx) ** 2 for x in xs)
    syy = sum((y - my) ** 2 for y in ys)
    return sxy / math.sqrt(sxx * syy) if sxx and syy else 0.0


if __name__ == "__main__":
    import sys

    n = int(sys.argv[1]) if len(sys.argv) > 1 else 2000
    pop = sample_population(n, seed=42)

    dims = list(LOADINGS.keys())
    cols = {d: [p["latent_traits_z"][d] for p in pop] for d in dims}

    print(f"Sampled {n} young-adult Iranian respondents. Empirical correlations (vs design):\n")
    checks = [
        ("internet_addiction", "loneliness", "pos"),
        ("parental_care", "loneliness", "neg"),
        ("dysfunctional_attitudes", "loneliness", "pos"),
        ("internet_addiction", "parental_care", "~0/neg"),
        ("dysfunctional_attitudes", "internet_addiction", "pos"),
    ]
    for a, b, expect in checks:
        r = _corr(cols[a], cols[b])
        print(f"  r({a}, {b}) = {r:+.2f}   [expected {expect}]")

    print("\nExample respondent:")
    ex = pop[0]
    print(f"  id: {ex['id']}")
    print(f"  demographics: {ex['demographics']}")
    print(f"  response_style: {ex['response_style']}")
    for d in dims:
        print(f"    {d:24s} z={ex['latent_traits_z'][d]:+.2f}  ({ex['latent_traits_band'][d]})")