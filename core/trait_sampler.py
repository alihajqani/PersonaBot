def _band(z: float) -> str:
    idx = 0
    for cut in BAND_CUTS:
        if z >= cut:
            idx += 1
    return BAND_LABELS[idx]


def _weighted_choice(rng: random.Random, items: List[tuple]):
    r = rng.random()
    cum = 0.0
    for label, w in items:
        cum += w
        if r <= cum:
            return label
    return items[-1][0]


def _sigmoid(x: float) -> float:
    if x >= 0:
        z = math.exp(-x)
        return 1.0 / (1.0 + z)
    z = math.exp(x)
    return z / (1.0 + z)


def sample_respondent(rng: random.Random, index: int) -> Dict:
    """Draw one synthetic respondent: latent traits + response style + demographics."""
    # --- common factors ---
    int_factor = rng.gauss(0, 1)   # internalizing / distress
    ext = rng.gauss(0, 1)          # externalizing / antagonism
    psy = rng.gauss(0, 1)          # psychoticism
    f = (int_factor, ext, psy)

    traits_z: Dict[str, float] = {}
    traits_band: Dict[str, str] = {}
    for dim, load in LOADINGS.items():
        ssq = sum(l * l for l in load)
        u = math.sqrt(max(1e-6, 1.0 - ssq))
        z = sum(l * fi for l, fi in zip(load, f)) + u * rng.gauss(0, 1)
        traits_z[dim] = round(z, 3)
        traits_band[dim] = _band(z)

    # --- response styles (method variance) ---
    response_style = {
        # >0 leans agree/high regardless of content; <0 leans disagree/low
        "acquiescence": round(rng.gauss(0, 0.40), 3),
        # >0 prefers the extreme categories; <0 hugs the midpoint
        "extreme_response": round(rng.gauss(0, 0.40), 3),
        # rare inattentive responder (near-random / straightlining)
        "careless": rng.random() < 0.04,
    }

    # --- demographics: urban Iranian adults, strictly 18-40 ---
    age = rng.randint(18, 40)
    gender = _weighted_choice(rng, GENDER_FRAME)
    marital_status = _weighted_choice(rng, MARITAL_FRAME)
    education = _weighted_choice(rng, EDUCATION_FRAME)
    occupation = _weighted_choice(rng, OCCUPATION_FRAME)
    region = _weighted_choice(rng, REGION_FRAME)
    economic = _weighted_choice(rng, ECONOMIC_FRAME)

    # Psychological-problem disclosure (history of psychiatric treatment):
    # trait-informed — high emotional instability and unusual experiences raise it.
    p = 0.10 + 0.18 * _sigmoid(traits_z["emotional_instability"]) + 0.12 * _sigmoid(traits_z["unusual_experiences"])
    p = max(0.03, min(0.55, p))
    psych_problem = "دارم" if rng.random() < p else "ندارم"

    return {
        "id": f"persona_{index}",
        "latent_traits_z": traits_z,
        "latent_traits_band": traits_band,
        "response_style": response_style,
        "demographics": {
            "gender": gender,
            "age": age,
            "marital_status": marital_status,
            "education_level": education,
            "occupation": occupation,
            "psych_problem": psych_problem,
            "region": region,
            "economic_situation": economic,
        },
    }


def sample_population(n: int, seed: int | None = None) -> List[Dict]:
    """Draw n synthetic respondents."""
    rng = random.Random(seed)
    return [sample_respondent(rng, i + 1) for i in range(n)]


# ---------------------------------------------------------------------------
# Self-test / demo:  python -m core.trait_sampler 2000
# Prints empirical correlations to confirm the intended structure emerges.
# ---------------------------------------------------------------------------

def _corr(xs: List[float], ys: List[float]) -> float:
    n = len(xs)
    mx = sum(xs) / n
    my = sum(ys) / n
    sxy = sum((x - mx) * (y - my) for x, y in zip(xs, ys))
    sxx = sum((x - mx) ** 2 for x in xs)
    syy = sum((y - my) ** 2 for y in ys)
    return sxy / math.sqrt(sxx * syy) if sxx and syy else 0.0


